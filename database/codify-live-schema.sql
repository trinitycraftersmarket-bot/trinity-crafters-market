-- ============================================================================
-- Codify the live schema (Phase 1, audit P0-2 / section 7.5)
-- ============================================================================
-- The live Supabase database is the only authoritative schema: a dozen tables
-- and many columns used by the code were never committed to this repo, and
-- several were created at runtime by ALTER TABLE statements inside request
-- handlers (audit section 5, pattern R-6). This file reconstructs those
-- definitions FROM THE CODE THAT USES THEM. Every statement is commented with
-- its file/line evidence. It is documentation-grade DDL:
--
--   * Every statement uses IF NOT EXISTS, so running it against the live DB
--     (where these objects already exist) is a no-op.
--   * Applied to a FRESH database after database/setup.sql, it brings that
--     database to parity with the schema the code expects.
--
-- Apply order for a fresh database:
--   1. database/setup.sql            (core tables + market.vendors, fixed)
--   2. database/codify-live-schema.sql   (this file)
--   3. database/vendor-credits.sql   (needs market.vendors + imported_attendees)
--   4. database/live-chat.sql, manager-rsvp.sql, manager-permissions.sql,
--      tumbler-expense-reconciliation.sql  (self-contained add-ons)
--
-- Conventions (from audit section 8): money is integer cents; RLS is enabled
-- on every table with anon/authenticated access revoked (access is only via
-- Netlify functions over DATABASE_URL); ids are uuid default gen_random_uuid()
-- unless the code shows otherwise.
--
-- Items that could NOT be verified from code alone are marked UNVERIFIED.
-- Known gaps are collected in the notes at the end of this file.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. market.vendors — master vendor records (audit section 8.8)
--    Also created by database/setup.sql (its live-chat section references this
--    table); the definition is repeated here so this file stands alone.
--    Evidence: insert columns — netlify/functions/api.mjs:333,
--    netlify/functions/manual-booking.mjs:124,
--    netlify/functions/vendor-admin.mjs:69; updated_at written at
--    vendor-admin.mjs:78 and ordered on at netlify/functions/live-chat.mjs:70;
--    email/phone/description are nullable in live (the data-quality scan at
--    netlify/functions/system-tools.mjs:8 looks for rows where they are NULL).
--    UNVERIFIED: account_number is never written by any code; it is generated
--    by the database on insert (vendor-admin.mjs:69 returns it from INSERT).
--    Its exact live type/default cannot be determined from code — every
--    consumer treats it as an opaque printable value.
-- ----------------------------------------------------------------------------
create table if not exists market.vendors(
  id uuid primary key default gen_random_uuid(),
  account_number bigint generated by default as identity,
  name text,
  business text,
  email text,
  phone text,
  billing_address text,
  description text,
  category_id uuid references market.categories,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table market.vendors enable row level security;
revoke all on market.vendors from anon,authenticated;

